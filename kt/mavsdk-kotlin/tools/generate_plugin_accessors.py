#!/usr/bin/env python3
"""Generate the plugin accessors that hang off System and ServerComponent.

protoc-gen-mavsdk runs once per .proto, so it cannot emit a file that aggregates
every plugin. This script fills that gap: it reads the `// plugin-target:` marker
that templates/file_kt.j2 writes into each generated plugin and emits one abstract
class per target holding a property for each plugin.

The accessors have to be *members* rather than extension properties so that callers
need only import the plugin type, not a separate extension. Members in turn require
a supertype for System/ServerComponent to inherit, and it has to be an abstract class
rather than an interface: Kotlin forbids `internal` on interface members, and the
plugin registry hooks below must not leak into the public API.
"""

from pathlib import Path
import re
import sys


ROOT = Path(__file__).resolve().parents[1]
COMMON = ROOT / "src/commonMain/kotlin/io/mavsdk/kotlin/plugins"
OUT_DIR = ROOT / "src/commonMain/kotlin/io/mavsdk/kotlin"

MARKER = re.compile(r"^// plugin-target: (System|ServerComponent)$", re.MULTILINE)

TARGETS = {
    "System": {
        "base": "SystemPlugins",
        "handle_arg": "systemHandle",
        "owner": "system",
    },
    "ServerComponent": {
        "base": "ServerComponentPlugins",
        "handle_arg": "serverComponentHandle",
        "owner": "server component",
    },
}


def fail(message: str) -> None:
    print(f"error: {message}", file=sys.stderr)
    raise SystemExit(1)


def lower_camel(name: str) -> str:
    return name[0].lower() + name[1:]


def collect() -> dict[str, list[tuple[str, str]]]:
    """Map each target to the (class name, package) pairs reached from it."""
    found: dict[str, list[tuple[str, str]]] = {target: [] for target in TARGETS}
    for path in sorted(COMMON.glob("*/*.kt")):
        match = MARKER.search(path.read_text())
        if not match:
            fail(
                f"{path.relative_to(ROOT)} has no '// plugin-target:' marker; "
                "regenerate it with templates/file_kt.j2"
            )
        # The directory is the package, so there is no need to infer one from the
        # class name -- Ftp/Rtk and friends do not round-trip through snake_case.
        found[match.group(1)].append((path.stem, path.parent.name))
    return found


def render(target: str, plugins: list[tuple[str, str]]) -> str:
    spec = TARGETS[target]
    base = spec["base"]

    imports = []
    for plugin, package_dir in plugins:
        package = f"io.mavsdk.kotlin.plugins.{package_dir}"
        imports.append(f"import {package}.{plugin}")
        imports.append(f"import {package}.create{plugin}Native")
    imports.append("import kotlin.reflect.KClass")

    accessors = []
    for plugin, _ in plugins:
        accessors.append(
            f"""
    /** The canonical {plugin} plugin for this {spec["owner"]}. */
    val {lower_camel(plugin)}: {plugin}
        get() =
            plugin(
                {plugin}::class,
                {{ {plugin}(create{plugin}Native(getHandle())) }},
                {plugin}::destroy,
            )"""
        )

    return f"""// WARNING: THIS FILE IS AUTOGENERATED! As such, it should not be edited.
// Regenerate it with tools/generate_plugin_accessors.py (run for you by
// tools/generate_from_protos.bash).

package io.mavsdk.kotlin

{chr(10).join(sorted(imports))}

/**
 * Plugin accessors for [{target}].
 *
 * Each property returns the one canonical plugin instance for its owner, creating it
 * on first access and reusing it thereafter, so repeated reads are cheap and every
 * caller shares the same subscriptions. The instance is destroyed when its owner is
 * closed; reading a property after that throws [IllegalStateException].
 *
 * This is an abstract class rather than an interface because the two hooks below must
 * stay `internal`, which Kotlin does not allow on interface members.
 */
abstract class {base} internal constructor() {{

    /** Native handle of the owning {spec["owner"]}. */
    internal abstract fun getHandle(): Long

    /** Returns the cached plugin of type [pluginClass], creating it on first access. */
    internal abstract fun <Plugin : Any> plugin(
        pluginClass: KClass<Plugin>,
        create: () -> Plugin,
        destroy: (Plugin) -> Unit,
    ): Plugin
{chr(10).join(accessors)}
}}
"""


def main() -> None:
    found = collect()
    for target, plugins in found.items():
        if not plugins:
            fail(f"no plugins found for target {target}")
        out = OUT_DIR / f"{TARGETS[target]['base']}.kt"
        out.write_text(render(target, plugins))
        print(f"Generated {out.relative_to(ROOT)} with {len(plugins)} accessors.")


if __name__ == "__main__":
    main()
